"""Writes crates/taco/src/tokenizer/unicode_tables.rs from the Python `regex` module.

The GPT-2 pre-tokenizer (tools/baseline/bpe.py) uses the classes \\p{L}, \\p{N} and \\s of the
`regex` module. The Rust tokenizer uses the same classes as fixed tables, so that its output
does not change with the Unicode version of the Rust toolchain (plan §10).

Run from the repository root:

    uv run --project tools python -I crates/taco/scripts/gen_unicode_tables.py \
        > crates/taco/src/tokenizer/unicode_tables.rs
"""

from __future__ import annotations

import regex

CLASSES = [
    ("LETTER", r"\p{L}", "`\\p{L}`: the Unicode general category Letter (Lu, Ll, Lt, Lm, Lo)."),
    ("NUMBER", r"\p{N}", "`\\p{N}`: the Unicode general category Number (Nd, Nl, No)."),
    ("WHITESPACE", r"\s", "`\\s`: the Unicode property White_Space."),
]


def ranges(pattern: str) -> list[tuple[int, int]]:
    """Return the closed ranges of code points that match `pattern`."""
    p = regex.compile(pattern)
    out: list[tuple[int, int]] = []
    start = None
    prev = 0
    for c in range(0x110000):
        ok = not 0xD800 <= c <= 0xDFFF and p.fullmatch(chr(c)) is not None
        if ok:
            if start is None:
                start = c
            prev = c
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def main() -> None:
    print("//! Unicode classes of the GPT-2 pre-tokenizer, as fixed tables.")
    print("//!")
    print("//! Generated by `crates/taco/scripts/gen_unicode_tables.py` with the Python `regex`")
    print(f"//! module {regex.__version__}. Do not edit by hand.")
    print("//!")
    print("//! DETERMINISM: the tables are data in the source. Thus the tokenizer gives the same")
    print("//! tokens with every Rust toolchain, and the same tokens as `tools/baseline/bpe.py`.")
    print()
    print("/// A sorted list of closed, disjoint ranges of code points.")
    print("pub(super) type Ranges = &'static [(u32, u32)];")
    for name, pattern, doc in CLASSES:
        rs = ranges(pattern)
        count = sum(b - a + 1 for a, b in rs)
        print()
        print(f"/// {doc}")
        print(f"/// {len(rs)} ranges, {count} code points.")
        print("#[rustfmt::skip]")
        print(f"pub(super) static {name}: Ranges = &[")
        line = "   "
        for a, b in rs:
            item = f" (0x{a:X}, 0x{b:X}),"
            if len(line) + len(item) > 99:
                print(line)
                line = "   "
            line += item
        if line.strip():
            print(line)
        print("];")


if __name__ == "__main__":
    main()
