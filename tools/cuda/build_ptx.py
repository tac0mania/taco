"""Compile the HardShell CUDA kernels to PTX with NVRTC (ADR 0008).

NVRTC runs only here, before publication. The PTX goes into the repository
(crates/hardshell-cuda/kernels/hardshell.ptx) and the crate embeds it. At run time
the GPU driver (libcuda) compiles the PTX for the GPU; no user installs NVRTC.

    python3 tools/cuda/build_ptx.py [--nvrtc /path/to/libnvrtc.so.12] [--check]

NVRTC comes from the official PyPI wheel nvidia-cuda-nvrtc-cu12==12.9.86, installed in a
Taco-owned cache on the build machine:

    uv pip install --target ~/.cache/taco/cuda/nvrtc-cu12-12.9.86 nvidia-cuda-nvrtc-cu12==12.9.86

--check compiles and compares with the committed PTX; it fails if they differ.
"""

import argparse
import ctypes
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "crates/hardshell-cuda/kernels/hardshell.cu"
OUT = ROOT / "crates/hardshell-cuda/kernels/hardshell.ptx"
DEFAULT_NVRTC = pathlib.Path.home() / ".cache/taco/cuda/nvrtc-cu12-12.9.86/nvidia/cuda_nvrtc/lib/libnvrtc.so.12"
# compute_80: Ampere and later (int8 mma.sync m16n8k32). The driver JIT-compiles it for sm_86.
OPTIONS = ["--gpu-architecture=compute_80", "--std=c++17", "--device-int128"]


def compile_ptx(nvrtc_path: pathlib.Path, source: bytes) -> tuple[bytes, str]:
    lib = ctypes.CDLL(str(nvrtc_path))
    major, minor = ctypes.c_int(), ctypes.c_int()
    lib.nvrtcVersion(ctypes.byref(major), ctypes.byref(minor))
    version = f"{major.value}.{minor.value}"
    prog = ctypes.c_void_p()
    rc = lib.nvrtcCreateProgram(ctypes.byref(prog), source, b"hardshell.cu", 0, None, None)
    if rc != 0:
        sys.exit(f"nvrtcCreateProgram failed: {rc}")
    opts = (ctypes.c_char_p * len(OPTIONS))(*[o.encode() for o in OPTIONS])
    rc = lib.nvrtcCompileProgram(prog, len(OPTIONS), opts)
    size = ctypes.c_size_t()
    lib.nvrtcGetProgramLogSize(prog, ctypes.byref(size))
    log = ctypes.create_string_buffer(size.value)
    lib.nvrtcGetProgramLog(prog, log)
    if rc != 0:
        sys.exit(f"NVRTC failed ({rc}):\n{log.value.decode(errors='replace')}")
    if log.value.strip():
        print(log.value.decode(errors="replace"), file=sys.stderr)
    lib.nvrtcGetPTXSize(prog, ctypes.byref(size))
    ptx = ctypes.create_string_buffer(size.value)
    lib.nvrtcGetPTX(prog, ptx)
    lib.nvrtcDestroyProgram(ctypes.byref(prog))
    return ptx.value, version


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--nvrtc", type=pathlib.Path, default=DEFAULT_NVRTC)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    source = SRC.read_bytes()
    ptx, version = compile_ptx(args.nvrtc, source)
    digest = hashlib.sha256(source).hexdigest()
    header = (
        f"// Generated by tools/cuda/build_ptx.py. Do not edit.\n"
        f"// source-sha256: {digest}\n"
        f"// nvrtc: {version}; options: {' '.join(OPTIONS)}\n"
    ).encode()
    text = header + ptx
    if args.check:
        if OUT.read_bytes() != text:
            sys.exit("the committed PTX differs from a new compile")
        print("PTX is current")
        return
    OUT.write_bytes(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(text)} bytes, NVRTC {version}, source {digest[:16]}")


if __name__ == "__main__":
    main()
